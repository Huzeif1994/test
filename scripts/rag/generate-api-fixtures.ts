import fs from 'fs';
import path from 'path';

/**
 * Requirements RAG: OpenAPI-to-Playwright API Client Generator
 * Ingests OpenAPI specifications and generates strongly typed Playwright API fixtures.
 */
export function generateApiClient(schemaPath: string, outputPath: string) {
  if (!fs.existsSync(schemaPath)) {
    throw new Error(`Schema file not found at: ${schemaPath}`);
  }

  const raw = fs.readFileSync(schemaPath, 'utf-8');
  const spec = JSON.parse(raw);

  const lines: string[] = [];
  lines.push(`// 🤖 AUTOGENERATED VIA SDET REQUIREMENTS RAG ENGINE`);
  lines.push(`// Source: ${path.basename(schemaPath)}`);
  lines.push(`// Generated: ${new Date().toISOString()}`);
  lines.push(``);
  lines.push(`import { APIRequestContext, expect } from '@playwright/test';`);
  lines.push(``);

  lines.push(`export class FTXApiClient {`);
  lines.push(`  constructor(private request: APIRequestContext, private baseUrl: string = 'https://ftx.dev.ftxcommerce.com/api/v1') {}`);
  lines.push(``);

  const paths = spec.paths || {};

  for (const [route, methods] of Object.entries<any>(paths)) {
    for (const [method, details] of Object.entries<any>(methods)) {
      if (['get', 'post', 'put', 'delete', 'patch'].includes(method.toLowerCase())) {
        const opId = details.operationId || `${method}${route.replace(/[\/{}]/g, '_')}`;
        const summary = details.summary || `${method.toUpperCase()} ${route}`;
        const hasPathParams = route.includes('{');
        const hasBody = ['post', 'put', 'patch'].includes(method.toLowerCase()) && details.requestBody;

        lines.push(`  /**`);
        lines.push(`   * ${summary}`);
        lines.push(`   * ${method.toUpperCase()} ${route}`);
        lines.push(`   */`);

        let paramSignature = '';
        if (hasPathParams) {
          const match = route.match(/\{([^}]+)\}/);
          const pName = match ? match[1] : 'id';
          paramSignature = `${pName}: string, `;
        }

        if (hasBody) {
          paramSignature += `payload: any`;
        } else if (!hasPathParams) {
          paramSignature = '';
        }

        // Clean up trailing comma
        paramSignature = paramSignature.replace(/,\s*$/, '');

        let urlExpression = `\`\${this.baseUrl}${route}\``;
        if (hasPathParams) {
          const match = route.match(/\{([^}]+)\}/);
          const pName = match ? match[1] : 'id';
          urlExpression = `\`\${this.baseUrl}${route.replace(`{${pName}}`, `\${${pName}}`)}\``;
        }

        lines.push(`  async ${opId}(${paramSignature}) {`);
        if (hasBody) {
          lines.push(`    const response = await this.request.${method.toLowerCase()}(${urlExpression}, { data: payload });`);
        } else {
          lines.push(`    const response = await this.request.${method.toLowerCase()}(${urlExpression});`);
        }
        lines.push(`    expect(response.ok(), \`API call ${opId} failed with status \${response.status()}\`).toBeTruthy();`);
        lines.push(`    return await response.json().catch(() => ({}));`);
        lines.push(`  }`);
        lines.push(``);
      }
    }
  }

  lines.push(`}`);

  const targetDir = path.dirname(outputPath);
  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  fs.writeFileSync(outputPath, lines.join('\n'), 'utf-8');
  console.log(`✅ Successfully generated typed API fixture: ${outputPath}`);
}

if (require.main === module) {
  const schemaFile = path.resolve(process.cwd(), 'schemas/ftx-commerce-openapi.sample.json');
  const targetOutput = path.resolve(process.cwd(), 'api/FTXApiClient.ts');

  console.log('\n==================================================');
  console.log('🧬 SDET REQUIREMENTS RAG — OpenAPI Generator');
  console.log('==================================================');
  console.log(`📖 Ingesting OpenAPI Specification: ${schemaFile}`);
  generateApiClient(schemaFile, targetOutput);
  console.log('==================================================\n');
}

